"""
Turns the silhouettes of Kannada personalities into js/silhouette-art.js. The
opening animation and the quotes section both draw from it (js/silhouette.js).

Each source image in assets/silhouettes/<id>.png is black on white, with one
highlighted feature in pure blue. The script traces two shapes from it: the whole
figure (black and blue together) and the blue accent alone, as smooth SVG paths.
The website colours both, so the source colours never reach the page.

Run from the project folder after adding or changing an image:
    python tools/silhouette-art.py
"""

import math
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "silhouettes"
OUTPUT = ROOT / "js" / "silhouette-art.js"

# Which way each figure faces as drawn; the page mirrors it where it needs to face the other way.
FACES = {
    "basavanna": "right",
    "kempegowda": "right",
    "obavva": "right",
    "chennamma": "left",
    "visvesvaraya": "left",
    "kuvempu": "left",
    "rajkumar": "left",
}

SCALE = 0.5  # output units per source pixel; keeps the paths small
MIN_AREA = 40  # source pixels; smaller blobs are stray specks
SIMPLIFY = 1.5  # source pixels a simplified outline may stray from the traced one
CORNER = math.radians(50)  # turns sharper than this stay crisp corners


def masks(path):
    """Figure mask (anything dark, including blue) and accent mask (blue only)."""
    image = cv2.imdecode(np.fromfile(path, dtype=np.uint8), cv2.IMREAD_COLOR).astype(int)
    blue, green, red = image[..., 0], image[..., 1], image[..., 2]
    figure = (blue + green + red) / 3 < 140
    accent = (blue > 100) & (blue - np.maximum(red, green) > 70)
    # Grown by a pixel so it covers the soft edge between blue and black; otherwise
    # a hairline of the figure colour shows around the accent.
    accent = cv2.dilate(accent.astype(np.uint8) * 255, np.ones((3, 3), np.uint8))
    return figure.astype(np.uint8) * 255, accent


def outlines(mask):
    """Simplified closed outlines, outer edges and holes alike (holes cut out by the even-odd fill)."""
    contours, _ = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    result = []
    for contour in contours:
        if abs(cv2.contourArea(contour)) < MIN_AREA:
            continue
        points = cv2.approxPolyDP(contour.astype(np.float32), SIMPLIFY, True).reshape(-1, 2)
        if len(points) >= 3:
            result.append(points)
    return result


def smooth_path(points, origin):
    """
    A closed path of cubic curves through the points. At smooth points the curve
    follows the line between the neighbours; at sharp corners it keeps the corner.
    """
    count = len(points)
    pts = [(np.asarray(p, dtype=float) - origin) * SCALE for p in points]

    def unit(v):
        length = np.hypot(*v)
        return v / length if length else v

    def tangent(i):
        before, here, after = pts[i - 1], pts[i], pts[(i + 1) % count]
        a, b = unit(here - before), unit(after - here)
        turn = math.acos(max(-1.0, min(1.0, float(np.dot(a, b)))))
        return None if turn > CORNER else unit(after - before)

    tangents = [tangent(i) for i in range(count)]
    fmt = lambda p: f"{p[0]:.1f} {p[1]:.1f}"
    parts = [f"M{fmt(pts[0])}"]
    for i in range(count):
        start, end = pts[i], pts[(i + 1) % count]
        length = np.hypot(*(end - start))
        direction = unit(end - start)
        out = tangents[i] if tangents[i] is not None else direction
        into = tangents[(i + 1) % count] if tangents[(i + 1) % count] is not None else direction
        c1, c2 = start + out * length / 3, end - into * length / 3
        parts.append(f"C{fmt(c1)} {fmt(c2)} {fmt(end)}")
    return "".join(parts) + "Z"


def trace(art_id):
    figure, accent = masks(SOURCE / f"{art_id}.png")
    x, y, w, h = cv2.boundingRect(cv2.findNonZero(figure))
    origin = np.array([x, y], dtype=float)
    return {
        "faces": FACES[art_id],
        "viewBox": f"0 0 {w * SCALE:.0f} {h * SCALE:.0f}",
        "body": "".join(smooth_path(p, origin) for p in outlines(figure)),
        "accent": "".join(smooth_path(p, origin) for p in outlines(accent)),
    }


def main():
    lines = [
        "/*",
        " * Silhouettes of Kannada personalities: each figure's outline (body) and its",
        " * highlighted feature (accent), as SVG paths, with the way it faces as drawn.",
        " * Generated by tools/silhouette-art.py from assets/silhouettes; do not edit by hand.",
        " */",
        "const SILHOUETTE_ART = {",
    ]
    for art_id in FACES:
        art = trace(art_id)
        lines.append(f"  {art_id}: {{")
        for key, value in art.items():
            lines.append(f'    {key}: "{value}",')
        lines.append("  },")
        print(f"{art_id}: {len(art['body']) + len(art['accent'])} characters")
    lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
